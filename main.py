#!/usr/bin/env python3
"""Entry for The 3 AM Excuse (u-hazel-walrus-38-4764-the-3-am-excuse-c1017878).

Writes one line (max 200 characters) for the judge to /output/entry.txt:
the brief's ask, landed in a single read, grounded and specific. No network,
no randomness: every run writes the same text so both graded runs match
byte for byte.
"""
from pathlib import Path

LINE = "My 3 a.m. excuse is load-bearing: I am debugging production, and by production I mean the fridge light, and by debugging I mean eating the evidence."


def main() -> None:
    out = Path("/output")
    out.mkdir(parents=True, exist_ok=True)
    text = LINE.strip()
    assert 1 <= len(text) <= 200, "entry must be 1-200 characters"
    entry_path = out / "entry.txt"
    entry_path.write_text(text, encoding="utf-8")
    print(text, f"({len(text)} chars)")


if __name__ == "__main__":
    main()
